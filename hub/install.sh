#!/usr/bin/env bash
# Pyra Claw hub installer for Raspberry Pi OS Bookworm (64-bit). Run with sudo.
# Idempotent: safe to re-run. Existing tokens and MQTT credentials are never overwritten.
#
# Options (flag or env var):
#   --no-ufw            / PYRA_NO_UFW=1        skip the firewall step
#   --allow-from "CIDR" / PYRA_ALLOW_FROM=...  space-separated subnets allowed to reach
#                                              8787/tcp, 1883/tcp and NTP 123/udp (default:
#                                              auto-detect the Pi's directly connected IPv4
#                                              subnets, incl. a USB gadget link if it is up)
#   --no-ntp            / PYRA_NO_NTP=1        don't set up chrony as the LAN NTP server
#   PYRA_SSH_PORT=22                           SSH port kept open (allowed first)
#   PYRA_NODE_MQTT_USER=pyra-node              MQTT username for the ESP32 node(s)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
[[ $EUID -eq 0 ]] || { echo "run as root (sudo)"; exit 1; }

NO_UFW="${PYRA_NO_UFW:-0}"
NO_NTP="${PYRA_NO_NTP:-0}"
ALLOW_FROM="${PYRA_ALLOW_FROM:-}"
SSH_PORT="${PYRA_SSH_PORT:-22}"
HUB_MQTT_USER="pyra-hub"
NODE_MQTT_USER="${PYRA_NODE_MQTT_USER:-pyra-node}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-ufw) NO_UFW=1 ;;
    --no-ntp) NO_NTP=1 ;;
    --allow-from) ALLOW_FROM="$2"; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown option: $1"; exit 1 ;;
  esac
  shift
done

CONF_DIR=/etc/pyra-claw
CONF="$CONF_DIR/config.toml"
CREDS="$CONF_DIR/node-credentials"          # root-only copy of the secrets for provisioning
PASSWD=/etc/mosquitto/pyra-claw.passwd
MOSQ_CONF=/etc/mosquitto/conf.d/pyra-claw.conf
gen() { python3 -c 'import secrets; print(secrets.token_urlsafe(32))'; }

PKGS=(python3 python3-venv mosquitto mosquitto-clients avahi-daemon)
[[ "$NO_UFW" == "1" ]] || PKGS+=(ufw)
[[ "$NO_NTP" == "1" ]] || PKGS+=(chrony)   # replaces systemd-timesyncd
apt-get update
apt-get install -y "${PKGS[@]}"

id pyra &>/dev/null || useradd --system --home /var/lib/pyra-claw --shell /usr/sbin/nologin pyra
install -d -o pyra -g pyra /var/lib/pyra-claw
install -d "$CONF_DIR" /opt/pyra-claw

python3 -m venv /opt/pyra-claw/venv
/opt/pyra-claw/venv/bin/pip install --upgrade pip
/opt/pyra-claw/venv/bin/pip install "$HERE"

# ---------- secrets (generated once, then reused) ----------
umask 077
if [[ -f "$CREDS" ]]; then
  # shellcheck disable=SC1090
  source "$CREDS"
fi
: "${HUB_MQTT_PASS:=$(gen)}"
: "${NODE_MQTT_PASS:=$(gen)}"
: "${NODE_HUB_TOKEN:=$(gen)}"
if [[ ! -f "$CREDS" ]]; then
  cat > "$CREDS" <<CREDS_EOF
# Pyra Claw secrets, generated by install.sh. Do not commit. Provision the node with:
#   python tools/provision.py /dev/ttyUSB0 provision mqtt_user=\$NODE_MQTT_USER mqtt_pass=\$NODE_MQTT_PASS hub_token=\$NODE_HUB_TOKEN
HUB_MQTT_USER='$HUB_MQTT_USER'
HUB_MQTT_PASS='$HUB_MQTT_PASS'
NODE_MQTT_USER='$NODE_MQTT_USER'
NODE_MQTT_PASS='$NODE_MQTT_PASS'
NODE_HUB_TOKEN='$NODE_HUB_TOKEN'
CREDS_EOF
  chmod 600 "$CREDS"
  echo "Wrote node/MQTT secrets to $CREDS (root only)"
fi
umask 022

# ---------- hub config ----------
if [[ ! -f "$CONF" ]]; then
  TOKEN="$(gen)"
  sed "s/CHANGE_ME\"/$TOKEN\"/" "$HERE/config.example.toml" > "$CONF"
  echo "Generated auth token (save it for the Android app): $TOKEN"
fi
# Fill MQTT creds and node.hub_token only where they are still empty/placeholder.
python3 - "$CONF" "$HUB_MQTT_USER" "$HUB_MQTT_PASS" "$NODE_HUB_TOKEN" <<'PY'
import re, sys, tomllib
path, user, pw, tok = sys.argv[1:]
text = open(path).read()
data = tomllib.loads(text)
def is_unset(v): return not v or str(v).startswith("CHANGE_ME")
def set_key(text, section, key, value):
    pat = re.compile(rf'(^\[{section}\][^\[]*?^{key}\s*=\s*)"[^"\n]*"', re.M | re.S)
    if pat.search(text):
        return pat.sub(lambda m: m.group(1) + f'"{value}"', text, count=1)
    if re.search(rf'^\[{section}\]', text, re.M):
        return re.sub(rf'^\[{section}\]\n', f'[{section}]\n{key} = "{value}"\n', text, count=1, flags=re.M)
    return text.rstrip("\n") + f'\n\n[{section}]\n{key} = "{value}"\n'
m, n = data.get("mqtt", {}), data.get("node", {})
if is_unset(m.get("username")): text = set_key(text, "mqtt", "username", user)
if is_unset(m.get("password")): text = set_key(text, "mqtt", "password", pw)
if is_unset(n.get("hub_token")): text = set_key(text, "node", "hub_token", tok)
open(path, "w").write(text)
PY
chmod 640 "$CONF"; chgrp pyra "$CONF"

# ---------- Mosquitto: network listener with auth ----------
if [[ ! -f "$PASSWD" ]]; then
  install -m 640 -o root -g mosquitto /dev/null "$PASSWD"
fi
add_mqtt_user() {  # never overwrites an existing user's password
  grep -q "^$1:" "$PASSWD" || mosquitto_passwd -b "$PASSWD" "$1" "$2"
}
add_mqtt_user "$HUB_MQTT_USER" "$HUB_MQTT_PASS"
add_mqtt_user "$NODE_MQTT_USER" "$NODE_MQTT_PASS"
chown root:mosquitto "$PASSWD"; chmod 640 "$PASSWD"
cat > "$MOSQ_CONF" <<MOSQ_EOF
# Managed by pyra-claw hub/install.sh
listener 1883
allow_anonymous false
password_file $PASSWD
MOSQ_EOF
systemctl enable mosquitto
systemctl restart mosquitto

# ---------- LAN / USB subnets that may reach the hub ----------
if [[ -z "$ALLOW_FROM" ]]; then
  ALLOW_FROM="$(ip -o -4 route show scope link 2>/dev/null \
    | awk '$1 ~ /\// && $3 !~ /^(docker|br-|veth)/ {print $1}' | sort -u | tr '\n' ' ')"
fi

# ---------- chrony: NTP server for the ESP32 nodes (signed pulses need real time) -------
# The node refuses signed commands until its clock is synced; with no internet (or a
# USB-only link) the Pi is its only time source. `local stratum 10 orphan` keeps serving
# the Pi's own clock when upstream servers are unreachable. The Pi 5 RTC (with a battery)
# or fake-hwclock keeps that clock sane across reboots.
CHRONY_CONF=/etc/chrony/conf.d/pyra-claw.conf
if [[ "$NO_NTP" != "1" ]]; then
  install -d /etc/chrony/conf.d
  {
    echo "# Managed by pyra-claw hub/install.sh"
    if [[ -n "${ALLOW_FROM// }" ]]; then
      for net in $ALLOW_FROM; do echo "allow $net"; done
    else
      echo "# no LAN subnet detected: allow RFC1918 ranges"
      echo "allow 10.0.0.0/8"; echo "allow 172.16.0.0/12"; echo "allow 192.168.0.0/16"
    fi
    echo "local stratum 10 orphan"
  } > "$CHRONY_CONF"
  grep -qE '^\s*confdir\s+/etc/chrony/conf.d' /etc/chrony/chrony.conf \
    || echo "confdir /etc/chrony/conf.d" >> /etc/chrony/chrony.conf
  systemctl enable chrony
  systemctl restart chrony
  echo "chrony: serving NTP to: ${ALLOW_FROM:-RFC1918}"
else
  echo "NTP step skipped (--no-ntp / PYRA_NO_NTP=1): nodes need internet NTP for signed pulses"
fi

# ---------- firewall (optional, on by default) ----------
if [[ "$NO_UFW" != "1" ]]; then
  ufw allow "$SSH_PORT/tcp" comment 'ssh (pyra-claw keeps this open)'   # first: no lockout
  ufw default deny incoming
  ufw default allow outgoing
  if [[ -n "${ALLOW_FROM// }" ]]; then
    for net in $ALLOW_FROM; do
      ufw allow from "$net" to any port 8787 proto tcp comment 'pyra-hub'
      ufw allow from "$net" to any port 1883 proto tcp comment 'mosquitto'
      ufw allow from "$net" to any port 5353 proto udp comment 'mdns (app hub discovery)'
      [[ "$NO_NTP" == "1" ]] || ufw allow from "$net" to any port 123 proto udp comment 'ntp (chrony for nodes)'
    done
    echo "Firewall: 8787/1883 (+123/udp NTP) allowed from: $ALLOW_FROM"
  else
    echo "Firewall: could not detect a LAN subnet; allowing 8787/1883 from anywhere"
    ufw allow 8787/tcp comment 'pyra-hub'
    ufw allow 1883/tcp comment 'mosquitto'
    ufw allow 5353/udp comment 'mdns (app hub discovery)'
    [[ "$NO_NTP" == "1" ]] || ufw allow 123/udp comment 'ntp (chrony for nodes)'
  fi
  ufw --force enable
  ufw status verbose || true
else
  echo "Firewall step skipped (--no-ufw / PYRA_NO_UFW=1)"
fi

# ---------- mDNS advertisement (app "Scan" finds the hub) ----------
install -d /etc/avahi/services
install -m 644 "$HERE/avahi/pyra-hub.service" /etc/avahi/services/pyra-hub.service
systemctl enable avahi-daemon
systemctl restart avahi-daemon || echo "avahi-daemon restart failed; the app can still connect by address"

install -m 644 "$HERE/systemd/pyra-hub.service" /etc/systemd/system/pyra-hub.service
systemctl daemon-reload
systemctl enable pyra-hub
systemctl restart pyra-hub
systemctl --no-pager status pyra-hub || true
echo "Provision the ESP32 with the values in $CREDS (sudo cat $CREDS)."
